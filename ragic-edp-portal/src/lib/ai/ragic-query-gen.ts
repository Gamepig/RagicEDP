export async function generateRagicQuery(
  prompt: string,
  correlationId: string,
): Promise<RagicQueryPlan> {
  try {
    const result = await generateText({
      model: getFastModel(),
      system: SYSTEM_PROMPT,
      prompt,
      tools: {
        query_ragic: tool({
          description: "查詢 Ragic 表單資料",
          inputSchema: z.object({
            sheetCode: z.string().describe("表單代碼 (10/20/30/40/41/50/60/70/80/99)"),
            where: z.string().optional().describe("篩選條件，格式：欄位ID,運算子,值"),
            limit: z.number().optional().describe("回傳筆數上限（預設 50）"),
            compareBq: z.boolean().optional().describe("是否同時查 BigQuery 比對"),
            bqCompareQuery: z.string().optional().describe("BigQuery 比對用的自然語言查詢"),
          }),
        }),
      },
      maxOutputTokens: 512,
    });

    const call = result.toolCalls[0];
    if (!call) {
      return { sheetCode: "50", limit: 50, compareBq: false };
    }

    const input = call.input as {
      sheetCode: string;
      where?: string;
      limit?: number;
      compareBq?: boolean;
      bqCompareQuery?: string;
    };

    return {
      sheetCode: input.sheetCode,
      where: input.where,
      limit: Math.min(input.limit ?? 50, 100),
      compareBq: input.compareBq ?? false,
      bqCompareQuery: input.bqCompareQuery,
    };
  } catch (err) {
    aiLog({
      level: "warn",
      correlationId,
      module: "ai_expert",
      action: "ragic_query",
      error: err instanceof Error ? err.message : String(err),
    });
    return { sheetCode: "50", limit: 50, compareBq: false };
  }
}
